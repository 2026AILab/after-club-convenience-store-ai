# ============================================
# 1. 道具を読みこむ（os / gradio / OpenAI を使えるようにする）
# ============================================
import os
import gradio as gr
from openai import OpenAI


# ============================================
# 2. AIとつなぐ準備をする
# ============================================
BASE_URL = "https://education-demo-app.services.ai.azure.com/openai/v1"
API_KEY = os.environ.get("AZURE_OPENAI_API_KEY")
if not API_KEY:
    raise RuntimeError("環境変数 AZURE_OPENAI_API_KEY が設定されていません。")

client = OpenAI(base_url=BASE_URL, api_key=API_KEY)


# ============================================
# 3. AIの役割・出力フォーマットを決める
# ============================================
system_prompt = """
あなたは部活帰りの学生のための近くのコンビニや商品を提案するアシスタントです。
ユーザーから受け取った条件に合わせて、コンビニや商品を提案してください。

【コンビニ1】
コンビニ名:(コンビニ名を表示)
距離：（入力された学校から徒歩でどれくらいの距離か、また最寄駅からはどれぐらいかかるのか）
商品名1:(入力された気分の味に基づいておすすめの商品名を表示)
詳細:(商品1の価格やグラムを表示)

商品名2:(入力された気分の味に基づいて商品1とは違った商品を表示)
詳細:(商品2の価格やグラムを表示)


【コンビニ2】
コンビニ名:(コンビニ名を表示)
距離：（入力された学校から徒歩でどれくらいの距離か、また最寄駅からはどれぐらいかかるのか）
商品名1:(入力された気分の味に基づいておすすめの商品名を表示)
詳細:(商品1の価格やグラムを表示)
商品名2:(入力された気分の味に基づいて商品1とは違った商品を表示)
詳細:(商品2の価格やグラムを表示)

メッセージ:(入力された疲れ具合に応じて励ましの一言を表示)

注意事項：
- 必ず2つ提案する
- 上記フォーマット以外の文章は出力しないでください。
- 受け取った条件で近くのコンビニを表示する
- 遠回りしすぎて時間がかかりすぎる案は避ける
- 入力された気分の味によっておすすめの商品を提示してください
- なるべく異なった企業のコンビニを提示する
- 疲れ具合を最大100%として入力された疲れ具合によって励ましの一言を表示する
"""


# ============================================
# 4. ボタンが押されるたびに呼ばれる関数を定義する
# ============================================
def teian(School, Station, Feel_tired, Feel_taste):
    user_prompt = f"""
    次の条件で近くのコンビニを2種類提案してください。

    在籍校：{School}
    最寄り駅：{Station}
    疲れ具合：{Feel_tired}
    気分の味：{Feel_taste}
    """

    res = client.chat.completions.create(
        model="gpt-5.4-mini",
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    )
    return res.choices[0].message.content


# ============================================
# 5. 入力欄つきの画面を作成して起動する
# ============================================
gr.Interface(
    fn=teian,
    inputs=[
        gr.Textbox(label="在籍校"),
        gr.Textbox(label="最寄り駅(中学.高校の)"),
        gr.Textbox(label="その日の疲れ具合を最大100%で入力"),
        gr.Textbox(label="その日の気分の味を入力（例：甘い、しょっぱい）"),
    ],
    outputs=gr.Textbox(label="AIからの提案", lines=10),
    title="コンビニ提案AI",
    submit_btn="コンビニを提案してもらう",
).launch(share=True, auth=("student", "edu2026"))